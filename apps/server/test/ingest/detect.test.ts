// Build plan Task 8, AC-020 and AC-024: which uploads are a supported file.
// The name picks the kind; the first bytes, and for a binary STL the size,
// must agree with it.
import { describe, expect, test } from "vitest";
import { detectKind, FIRST_BYTES } from "../../src/ingest/detect.js";

const ZIP = Buffer.from([0x50, 0x4b, 0x03, 0x04, 0x14, 0x00, 0x00, 0x00]);
const asciiStl = Buffer.from("solid cube\n facet normal 0 0 1\n", "ascii");
/** A binary STL: 80-byte header, triangle count, 50 bytes per triangle. */
function binaryStlOf(triangles: number): Buffer {
  const b = Buffer.alloc(84 + 50 * triangles);
  b.write("solid looking header of a binary stl", 0, "ascii");
  b.writeUInt32LE(triangles, 80);
  return b;
}
const binaryStl = binaryStlOf(1);
/** A PNG signature and IHDR, padded past 84 bytes. */
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d]),
  Buffer.from("IHDR", "ascii"),
  Buffer.alloc(184),
]);
const gcode = Buffer.from(
  `; generated by a slicer\nG28\n${"G1 X10 Y10 E0.5\n".repeat(10)}`,
  "ascii",
);
const step = Buffer.from("ISO-10303-21;\nHEADER;\n", "ascii");
const scad = Buffer.from("cube([10, 10, 10]);\n", "utf8");

describe("detectKind", () => {
  test.each([
    ["Model.3mf", ZIP, "3mf"],
    ["MODEL.3MF", ZIP, "3mf"],
    ["part.stl", asciiStl, "stl"],
    ["part.STL", binaryStl, "stl"],
    ["bracket.step", step, "step"],
    ["bracket.stp", step, "step"],
    ["bracket.STP", Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), step]), "step"],
    ["box.scad", scad, "scad"],
    ["box.scad", Buffer.from("// caf\u00e9 \u2013 a comment\ncube(1);\n", "utf8"), "scad"],
    ["dir/sub dir/Plate one.3mf", ZIP, "3mf"],
    ["part.stl", binaryStlOf(0), "stl"],
  ])("%s is %s", (name, bytes, kind) => {
    expect(detectKind(name, bytes, bytes.length)).toBe(kind);
  });

  test("a large binary STL is recognised from its first bytes and its size", () => {
    const triangles = 100_000;
    const head = binaryStlOf(0);
    head.writeUInt32LE(triangles, 80);
    expect(detectKind("big.stl", head, 84 + 50 * triangles)).toBe("stl");
  });

  test.each([
    ["an unsupported extension", "model.obj", ZIP],
    ["G-code", "plate.gcode", Buffer.from("; G-code\n")],
    ["no extension", "model", ZIP],
    ["a dotfile named like an extension", ".3mf", ZIP],
    ["an extension only in the middle", "model.3mf.zip", ZIP],
    ["a .3mf that is not a zip", "model.3mf", Buffer.from("not a zip at all")],
    ["an empty .3mf", "model.3mf", Buffer.alloc(0)],
    ["a .scad with a NUL byte", "box.scad", Buffer.from([0x63, 0x00, 0x75])],
    ["a .scad that is not UTF-8", "box.scad", Buffer.from([0x63, 0xff, 0xfe, 0x75])],
    ["an empty .stl", "part.stl", Buffer.alloc(0)],
    ["a binary .stl shorter than its header and count", "part.stl", Buffer.alloc(83)],
    ["a .step without the ISO-10303-21 header", "part.step", Buffer.from("HEADER;\n")],
    ["a .stp that is a zip", "part.stp", ZIP],
    // 84 bytes or more, named .stl, but not an STL (AC-024).
    ["a PNG named .stl", "part.stl", png],
    ["a zip named .stl", "part.stl", Buffer.concat([ZIP, Buffer.alloc(200)])],
    ["G-code named .stl", "plate_1.stl", gcode],
    [
      "a binary .stl one byte longer than its triangles",
      "part.stl",
      Buffer.concat([binaryStl, Buffer.alloc(1)]),
    ],
    [
      "a binary .stl one byte shorter than its triangles",
      "part.stl",
      binaryStl.subarray(0, binaryStl.length - 1),
    ],
  ])("refuses %s", (_label, name, bytes) => {
    expect(detectKind(name, bytes, bytes.length)).toBeNull();
  });

  test("the files refused as not an STL are 84 bytes or more, so size alone never passed them", () => {
    for (const bytes of [png, gcode]) expect(bytes.length).toBeGreaterThanOrEqual(84);
  });

  test("a .scad cut mid-character at the end of the sample is still text", () => {
    const text = Buffer.from(`${"x".repeat(FIRST_BYTES - 1)}\u00e9`, "utf8");
    expect(detectKind("box.scad", text.subarray(0, FIRST_BYTES), text.length)).toBe("scad");
  });
});
