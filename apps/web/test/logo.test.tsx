describe("index.html links the icons and the manifest", () => {
  const html = readFileSync(new URL("../index.html", import.meta.url), "utf8");
  const links = [...html.matchAll(/<link\b[^>]*>/g)].map((m) => m[0]);

  test("in place of the empty data: icon", () => {
    expect(html).not.toContain("data:,");
  });

  test.each([
    ['rel="icon"', 'href="/favicon.ico"', 'sizes="32x32"'],
    ['rel="icon"', 'href="/favicon.svg"', 'type="image/svg+xml"'],
    ['rel="apple-touch-icon"', 'href="/apple-touch-icon.png"'],
    ['rel="manifest"', 'href="/site.webmanifest"'],
  ])("a link %s %s", (...parts) => {
    expect(links.some((link) => parts.every((part) => link.includes(part)))).toBe(true);
  });

  test("every linked file is in public/", () => {
    for (const link of links) {
      const href = /\shref="\/([^"]+)"/.exec(link)?.[1];
      if (href === undefined) continue;
      expect(existsSync(new URL(href, PUBLIC)), href).toBe(true);
    }
  });
});

describe("the static files are generated from one accent", () => {
  test("the accent is Blueprint indigo; the app icons are white on a deeper indigo tile", () => {
    expect(ACCENT).toBe("#5560e0");
    expect(ICON_TILE).toBe("#3d47c4");
    expect(ICON_ART).toBe("#ffffff");
    expect(TILE).toBe("#121418");
  });

  test("the tiled PNGs are drawn from ICON_TILE and ICON_ART, the ICO frames from ACCENT", () => {
    for (const icon of ICON_PNGS) {
      const svg = tiledSvg(icon);
      expect(svg, icon.file).toContain(`fill="${ICON_TILE}"`);
      expect(svg, icon.file).toContain(`stroke="${ICON_ART}"`);
      expect(svg, icon.file).not.toContain(ACCENT);
    }
    for (const frame of ICO_FRAMES) {
      const svg = frameSvg(frame);
      expect(svg).toContain(`stroke="${ACCENT}"`);
      expect(svg).toContain(`stroke-width="${frame.art === "small" ? 7 : 6}"`);
      expect(svg).toContain(`width="${frame.size}"`);
    }
  });

  test.each(Object.keys(TEXT_OUTPUTS))("%s is what the generator writes", (path) => {
    const committed = readFileSync(new URL(path, ROOT), "utf8");
    expect(committed).toBe(TEXT_OUTPUTS[path]);
  });

  test("the SVG files use the accent and no other colour", () => {
    for (const [path, text] of Object.entries(TEXT_OUTPUTS)) {
      if (!path.endsWith(".svg")) continue;
      const colours = new Set([...text.matchAll(/#[0-9a-f]{6}\b/gi)].map((m) => m[0]));
      expect([...colours], path).toEqual([ACCENT]);
    }
  });

  test("the manifest names Platehouse, its colours and every app icon", () => {
    const manifest = JSON.parse(manifestText());
    expect(manifest.name).toBe("Platehouse");
    expect(manifest.short_name).toBe("Platehouse");
    expect(manifest.theme_color).toBe(ACCENT);
    expect(manifest.background_color).toBe(TILE);
    expect(manifest.icons).toEqual([
      { src: "/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
      { src: "/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
      { src: "/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
    ]);
    for (const icon of manifest.icons) {
      const file = icon.src.slice(1);
      const { width, height } = pngSize(bytes(new URL(file, PUBLIC)));
      expect(`${width}x${height}`, file).toBe(icon.sizes);
    }
  });

  test.each(ICON_PNGS.map((icon) => [icon.file, icon.size]))(
    "%s is a %d px square PNG",
    (file, size) => {
      expect(pngSize(bytes(new URL(file, PUBLIC)))).toEqual({ width: size, height: size });
    },
  );

  test("the apple-touch icon is 180 px on a solid tile; the maskable one fills its tile", () => {
    const apple = ICON_PNGS.find((icon) => icon.file === "apple-touch-icon.png");
    const maskable = ICON_PNGS.find((icon) => icon.file === "icon-maskable-512.png");
    expect(apple).toMatchObject({ size: 180, tile: "square" });
    expect(maskable).toMatchObject({ size: 512, tile: "square" });
  });

  // The maskable icon's safe zone is the circle of radius 40% of the icon at
  // its centre: the art, stroke caps included, must sit inside it.
  test("the maskable icon's art sits inside the safe zone", () => {
    const maskable = ICON_PNGS.find((icon) => icon.file === "icon-maskable-512.png");
    expect(maskable).toBeDefined();
    const { size, inner } = maskable as { size: number; inner: number };
    const scale = inner / 64;
    const offset = (size - inner) / 2;
    const half = FULL_ART.roof.strokeWidth / 2;
    const distance = (x: number, y: number) =>
      Math.hypot(offset + x * scale - size / 2, offset + y * scale - size / 2);
    // The roof's ends and apex are round caps and a round join: the stroke
    // reaches half its width past each point, in every direction.
    for (const [x, y] of [
      [9, 29],
      [32, 10],
      [55, 29],
    ] as const) {
      expect(distance(x, y) + half * scale, `roof ${x},${y}`).toBeLessThanOrEqual(size * 0.4);
    }
    // Every layer's corners (the rounded corners sit inside them).
    for (const l of FULL_ART.layers) {
      for (const [x, y] of [
        [l.x, l.y],
        [l.x + l.width, l.y],
        [l.x, l.y + l.height],
        [l.x + l.width, l.y + l.height],
      ] as const) {
        expect(distance(x, y), `layer ${x},${y}`).toBeLessThanOrEqual(size * 0.4);
      }
    }
  });

  test("favicon.ico holds a 16 px frame of the small art and a 32 px frame of the full art", () => {
    expect(ICO_FRAMES).toEqual([
      { size: 16, art: "small" },
      { size: 32, art: "full" },
    ]);
    const frames = readIco(bytes(new URL("favicon.ico", PUBLIC)));
    expect(frames.map((f) => f.size)).toEqual([16, 32]);
    for (const frame of frames) {
      expect(pngSize(frame.png)).toEqual({ width: frame.size, height: frame.size });
    }
  });
});

describe("encodeIco and readIco", () => {
  // A 1 x 1 PNG header is enough: ICO only stores the bytes and the size.
  function fakePng(size: number): Uint8Array {
    const png = new Uint8Array(33);
    png.set([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a], 0);
    const view = new DataView(png.buffer);
    view.setUint32(8, 13);
    png.set([0x49, 0x48, 0x44, 0x52], 12);
    view.setUint32(16, size);
    view.setUint32(20, size);
    return png;
  }

  test("writes the ICONDIR header, one entry per frame and the PNG bytes after them", () => {
    const a = fakePng(16);
    const b = fakePng(32);
    const ico = encodeIco([
      { size: 16, png: a },
      { size: 32, png: b },
    ]);
    const view = new DataView(ico.buffer, ico.byteOffset, ico.byteLength);
    expect([view.getUint16(0, true), view.getUint16(2, true), view.getUint16(4, true)]).toEqual([
      0, 1, 2,
    ]);
    expect(ico[6]).toBe(16);
    expect(view.getUint32(6 + 8, true)).toBe(a.length);
    expect(view.getUint32(6 + 12, true)).toBe(6 + 2 * 16);
    expect(ico[22]).toBe(32);
    expect(view.getUint32(22 + 12, true)).toBe(6 + 2 * 16 + a.length);
    expect(ico.length).toBe(6 + 2 * 16 + a.length + b.length);
    expect(readIco(ico)).toEqual([
      { size: 16, png: a },
      { size: 32, png: b },
    ]);
  });

  test("a 256 px frame is written as 0, as ICO requires", () => {
    const ico = encodeIco([{ size: 256, png: fakePng(256) }]);
    expect(ico[6]).toBe(0);
    expect(readIco(ico)[0]?.size).toBe(256);
  });

  test("refuses a frame over 256 px and bytes that are not a PNG", () => {
    expect(() => encodeIco([{ size: 512, png: fakePng(512) }])).toThrow(/256/);
    expect(() => pngSize(new Uint8Array(33))).toThrow(/PNG/);
  });
});
